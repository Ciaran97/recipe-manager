import XCTest

final class CatalogueUITests: XCTestCase {
    @MainActor func testCatalogueCorrectionAliasesCategoriesAndReferenceSafety() async throws {
        guard ProcessInfo.processInfo.environment["RECIPE_MANAGER_RUN_E2E"] == "1" else { throw XCTSkip("Run the isolated native fixture with CatalogueUITests.") }
        continueAfterFailure = false
        let api = try NativeFixtureAPI(); try await api.login()
        let app = XCUIApplication(); app.launch()
        XCTAssertTrue(app.tabBars.buttons["Settings"].waitForExistence(timeout: 20)); app.tabBars.buttons["Settings"].tap()
        featureTap(app.buttons["Ingredient catalogue"], in: app)
        featureTap(app.buttons["New ingredient"], in: app)
        featureEnter(app.textFields["ingredient-name"], "Red capscum", in: app)
        featureTap(app.buttons["Save ingredient"], in: app); featureNotice("Ingredient saved.", in: app)
        featureEnter(app.textFields["ingredient-name"], "Red capsicum", in: app, replace: true)
        featureTap(app.switches["Keep previous name as alias"], in: app)
        featureTap(app.buttons["ingredient-category"], in: app)
        app.buttons["Produce"].tap()
        featureTap(app.buttons["Save ingredient"], in: app); featureNotice("Ingredient saved.", in: app)
        featureEnter(app.textFields["ingredient-alias"], "Red pepper", in: app)
        featureTap(app.buttons["Save alias"], in: app); featureNotice("Alias saved.", in: app)
        featureTap(app.buttons["Edit Red pepper"], in: app)
        featureEnter(app.textFields["ingredient-alias"], "Sweet pepper", in: app, replace: true)
        featureTap(app.buttons["Save alias"], in: app); featureNotice("Alias saved.", in: app)
        let (catalogue, _) = try await api.read("/api/v1/ingredients")
        let ingredient = try XCTUnwrap((catalogue["items"] as? [[String: Any]])?.first { $0["canonicalName"] as? String == "Red capsicum" })
        let id = try XCTUnwrap(ingredient["id"] as? String)
        featureTap(app.buttons["Done"], in: app)
        featureEnter(app.searchFields.firstMatch, "Sweet pepper", in: app)
        app.keyboards.buttons["Search"].tap()
        featureTap(app.buttons["ingredient-row-" + id], in: app)
        _ = try await api.write("POST", "/api/v1/ingredients", body: ["canonicalName": "Beef mince"], expected: 201)
        featureEnter(app.textFields["ingredient-alias"], "Beef mince", in: app)
        featureTap(app.buttons["Save alias"], in: app)
        XCTAssertTrue(app.staticTexts.matching(identifier: "catalogue-error").firstMatch.waitForExistence(timeout: 10))
        XCTAssertTrue(app.staticTexts.matching(identifier: "catalogue-error").firstMatch.label.contains("name is already in use"))
        let recipeId = try await api.seedRecipe(ingredientId: id)
        featureEnter(app.textFields["ingredient-alias"], "", in: app, replace: true)
        featureEnter(app.textFields["ingredient-name"], "Red bell pepper", in: app, replace: true)
        featureTap(app.buttons["Save ingredient"], in: app); featureNotice("Ingredient saved.", in: app)
        let (recipe, _) = try await api.read("/api/v1/recipes/" + recipeId)
        let row = try XCTUnwrap((recipe["ingredients"] as? [[String: Any]])?.first)
        XCTAssertEqual(row["ingredientId"] as? String, id); XCTAssertEqual(row["ingredientName"] as? String, "Red bell pepper")
        featureTap(app.buttons["Delete ingredient"], in: app); featureConfirm("Delete ingredient", in: app)
        XCTAssertTrue(app.staticTexts.matching(identifier: "catalogue-error").firstMatch.waitForExistence(timeout: 10)); XCTAssertTrue(app.staticTexts.matching(identifier: "catalogue-error").firstMatch.label.contains("used"))
        featureTap(app.buttons["Remove Sweet pepper"], in: app); featureNotice("Alias removed.", in: app)
        featureTap(app.buttons["Done"], in: app)
        featureEnter(app.searchFields.firstMatch, "", in: app, replace: true)
        featureTap(app.buttons["Manage shopping categories"], in: app)
        featureEnter(app.textFields["Category name"], "Frozen", in: app)
        featureEnter(app.textFields["Display order"], "4", in: app, replace: true)
        featureTap(app.buttons["Save category"], in: app); featureNotice("Category saved.", in: app)
        featureTap(app.buttons["Done"], in: app)
        featureTap(app.buttons["ingredient-row-" + id], in: app)
        featureTap(app.buttons["ingredient-category"], in: app); app.buttons["Frozen"].tap()
        featureTap(app.buttons["Save ingredient"], in: app); featureNotice("Ingredient saved.", in: app)
        featureTap(app.buttons["Done"], in: app)
        featureTap(app.buttons["Manage shopping categories"], in: app)
        featureTap(app.buttons["Delete category"], in: app); featureConfirm("Delete category", in: app); featureNotice("Category deleted.", in: app)
        featureTap(app.buttons["Done"], in: app)
        featureTap(app.buttons["ingredient-row-" + id], in: app)
        XCTAssertTrue(app.buttons["ingredient-category"].label.contains("Uncategorized"))
        let (_, current) = try await api.read("/api/v1/recipes/" + recipeId)
        _ = try await api.write("DELETE", "/api/v1/recipes/" + recipeId, etag: current.value(forHTTPHeaderField: "ETag"), expected: 204)
        featureTap(app.buttons["Delete ingredient"], in: app); featureConfirm("Delete ingredient", in: app)
        XCTAssertTrue(app.buttons["New ingredient"].waitForExistence(timeout: 10))
    }
}
