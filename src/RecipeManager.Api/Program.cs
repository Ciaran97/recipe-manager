builder.Services.AddSingleton<RecipeManager.Core.Modules.Imports.ITextRecipeImporter, RecipeManager.Infrastructure.Imports.AiTextImporter>();
builder.Services.AddScoped<RecipeManager.Infrastructure.Imports.ExpiredDraftCleanup>();
if (!generating && !testing) builder.Services.AddHostedService<RecipeManager.Api.Imports.ImportCleanupWorker>();
builder.Services.AddScoped<IRecipeSnapshotSource, RecipeSnapshotReader>();
