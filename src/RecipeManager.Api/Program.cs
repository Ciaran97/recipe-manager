app.UseMaintenanceBoundary();
app.UseApiStatusPages();
app.Use(async (context, next) =>
{
    if (context.Request.Path.StartsWithSegments("/api/v1")) context.Response.Headers.CacheControl = "no-store";
    await next(context);
