if (args.FirstOrDefault() == "maintenance")
    return await ResetPasswordCommand.RunAsync(args[1..], new ConfigurationBuilder().AddEnvironmentVariables().Build());

if (args.FirstOrDefault() == "migrate")
    return args.Length == 1 ? await MigrateCommand.RunAsync(new ConfigurationBuilder().AddEnvironmentVariables().Build()) : 2;
if (args.FirstOrDefault() == "healthcheck")
    return args.Length == 1 ? await HealthProbeCommand.RunAsync() : 2;

var builder = WebApplication.CreateBuilder(args);
var generating = Assembly.GetEntryAssembly()?.GetName().Name == "GetDocument.Insider";
var testing = builder.Environment.IsEnvironment("Testing");
builder.ConfigureMaintenance(generating);
builder.ConfigurePublicHost();
builder.Logging.ClearProviders();
builder.Logging.AddJsonConsole(options => options.UseUtcTimestamp = true);
builder.Logging.AddFilter("Microsoft.EntityFrameworkCore", LogLevel.None);
builder.Logging.AddFilter("Microsoft.AspNetCore.Hosting.Diagnostics", LogLevel.Warning);
builder.Logging.AddFilter("System.Net.Http.HttpClient", LogLevel.None);
builder.Services.AddProblemDetails();
builder.Services.AddExceptionHandler<ApiExceptionHandler>();
builder.Services.ConfigureHttpJsonOptions(options =>
{
    TransportConventions.Configure(options.SerializerOptions);
    options.SerializerOptions.UnmappedMemberHandling = System.Text.Json.Serialization.JsonUnmappedMemberHandling.Disallow;
    options.SerializerOptions.RespectNullableAnnotations = true;
    options.SerializerOptions.RespectRequiredConstructorParameters = true;
});
builder.Services.AddContractOpenApi();
builder.Services.Configure<RouteHandlerOptions>(options => options.ThrowOnBadRequest = true);
builder.Services.AddHouseholdRateLimits();
builder.AddRecipeImages(generating || testing);
KeyProtection.Configure(builder.Services, builder.Configuration, generating || testing);
builder.Services.AddDbContext<RecipeManagerDbContext>((services, options) =>
    options.UseNpgsql(SecretConfiguration.DatabaseConnection(services.GetRequiredService<IConfiguration>())));
builder.Services.AddRecipeManagerAuthentication();
builder.Services.AddScoped<RevisionCoordinator>();
