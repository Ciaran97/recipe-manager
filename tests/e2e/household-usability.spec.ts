import { test, expect } from '@playwright/test';
import { authenticatedHousehold, write } from './fixtures';

test('kitchen measures, inline organisers and adding recipe and planner ingredients to lists', async ({ page }) => {
  await authenticatedHousehold(page);
  const ingredient = await (await write(page, 'POST', '/api/v1/ingredients', { canonicalName: 'Salt' })).json();
  await page.goto('/recipes/new');
  await page.getByLabel('Title', { exact: true }).fill('Pinch of salt');
  await page.getByLabel('Default servings', { exact: true }).fill('2');
  await page.getByLabel('Cup and spoon standard').selectOption('AU');
  await page.getByRole('combobox', { name: 'Ingredient name 1', exact: true }).fill('Salt');
  await page.getByRole('option', { name: /^Salt/ }).click();
  await expect(page.getByLabel('Quantity 1', { exact: true })).toBeFocused();
  await page.getByLabel('Quantity 1', { exact: true }).fill('1');
  await page.getByLabel('Unit 1', { exact: true }).selectOption('pinch');
  await page.getByLabel('Step 1', { exact: true }).fill('Season to taste.');
  await page.getByRole('button', { name: 'Choose collections and tags', exact: true }).click();
  await page.getByLabel('New collection name', { exact: true }).fill('Small dinners');
  await page.getByRole('button', { name: 'Create collection', exact: true }).click();
  await expect(page.getByRole('checkbox', { name: 'Small dinners', exact: true })).toBeChecked();
  await page.getByLabel('New tag name', { exact: true }).fill('Simple');
  await page.getByRole('button', { name: 'Create tag', exact: true }).click();
  await expect(page.getByRole('checkbox', { name: 'Simple', exact: true })).toBeChecked();
  await expect(page.getByLabel('Title', { exact: true })).toHaveValue('Pinch of salt');
  await page.getByRole('button', { name: 'Save recipe', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Pinch of salt', exact: true })).toBeVisible();
  const recipeId = page.url().split('/').at(-1)!;
  await page.getByRole('link', { name: 'Add ingredients to shopping list', exact: true }).click();
  await page.getByRole('button', { name: 'Create new list with these ingredients', exact: true }).click();
  await page.getByLabel('List name', { exact: true }).fill('This week');
  await page.getByRole('button', { name: 'Create shopping list', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Shopping list created.');
  const lists = await (await page.request.get('/api/v1/shopping-lists')).json();
  const listId = lists.items[0].id;
  const before = await (await page.request.get(`/api/v1/shopping-lists/${listId}`)).json();
  expect(before.items[0].dimension).toBe('Pinch');
  // Category changes use intact validators and retain the same ingredient identity.
  await page.goto('/ingredients');
  await page.getByRole('button', { name: /^Salt/ }).click();
  const categories = await (await page.request.get('/api/v1/ingredient-categories')).json();
  await page.getByRole('combobox', { name: 'Shopping category', exact: true }).selectOption(categories.items[0].id);
  await page.getByRole('button', { name: 'Save ingredient', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Ingredient saved.');
  expect((await (await page.request.get(`/api/v1/ingredients/${ingredient.id}`)).json()).categoryId).toBe(categories.items[0].id);
  // A cooking source on the displayed week is added alongside the recipe, preserving provenance.
  await page.goto('/meal-planner');
  const week = await page.locator('#planner-week').inputValue();
  const slots = await (await page.request.get('/api/v1/meal-slots')).json();
  expect((await write(page, 'POST', '/api/v1/meals/cooking', { recipeId, date: week, slotId: slots.items[0].id, plannedPrepared: '2', plannedEaten: '2' })).status()).toBe(201);
  await page.getByRole('link', { name: "Add this week's ingredients to shopping list", exact: true }).click();
  await page.getByRole('button', { name: 'Add to This week', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Apply reviewed requirements', exact: true })).toBeVisible();
  const review = page.getByRole('checkbox', { name: 'I reviewed the latest requirements and choices', exact: true });
  if (await review.isVisible()) await review.check();
  await page.getByRole('button', { name: 'Apply reviewed requirements', exact: true }).click();
  const result = await (await page.request.get(`/api/v1/shopping-lists/${listId}`)).json();
  await expect.poll(async () => (await (await page.request.get(`/api/v1/shopping-lists/${listId}`)).json()).selection.kind).toBe('combined');
  expect(result.items[0].ingredientId).toBe(ingredient.id);
});
