import { test, expect } from '@playwright/test';
import { authenticatedHousehold, write } from './fixtures';

test('structured recipe editing, unresolved quantities, scaling and lifecycle retain original values', async ({ page }) => {
  await authenticatedHousehold(page);
  for (const canonicalName of ['Rice', 'Salt']) expect((await write(page, 'POST', '/api/v1/ingredients', { canonicalName })).status()).toBe(201);
  await page.goto('/recipes/new');
  await page.getByLabel('Title', { exact: true }).fill('Household rice');
  await page.getByLabel('Default servings', { exact: true }).fill('2');
  await expect(page.getByLabel('Cup and spoon standard')).toHaveValue('AU');
  await page.getByRole('combobox', { name: 'Ingredient name 1', exact: true }).fill('Rice');
  await page.getByRole('option', { name: 'Rice', exact: true }).click();
  await page.getByLabel('Quantity 1', { exact: true }).fill('1/2');
  await page.getByLabel('Unit 1', { exact: true }).selectOption('cup');
  await page.getByRole('button', { name: 'Duplicate ingredient 1', exact: true }).click();
  await page.getByRole('combobox', { name: 'Ingredient name 2', exact: true }).fill('Salt');
  await page.getByRole('option', { name: 'Salt', exact: true }).click();
  await page.getByLabel('Quantity 2', { exact: true }).fill('to taste');
  await page.getByLabel('Quantity unspecified for ingredient 2', { exact: true }).check();
  await page.getByRole('button', { name: 'Move ingredient 2 up', exact: true }).click();
  await expect(page.getByLabel('Quantity 1', { exact: true })).toHaveValue('to taste');
  await page.getByLabel(/I have reviewed/).check();
  await page.getByLabel('Step 1', { exact: true }).fill('Cook the rice, then season.');
  await page.getByRole('button', { name: 'Save recipe', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Household rice', exact: true })).toBeVisible();
  await expect(page.locator('.ingredient-lines')).toContainText('to taste');
  const id = page.url().split('/').at(-1);
  const original = await (await page.request.get(`/api/v1/recipes/${id}`)).json();
  expect(original.ingredients.map((line: { quantityText: string }) => line.quantityText)).toEqual(['to taste', '1/2']);
  await page.getByLabel('Preview servings', { exact: true }).fill('4');
  await page.getByRole('button', { name: 'Preview quantities', exact: true }).click();
  await expect(page.locator('.ingredient-lines')).toContainText('1 cup');
  await expect(page.locator('.ingredient-lines')).toContainText('to taste');
  expect((await (await page.request.get(`/api/v1/recipes/${id}`)).json()).ingredients[1].quantityText).toBe('1/2');
  await page.getByRole('link', { name: 'Edit recipe', exact: true }).click();
  await page.getByLabel('Title', { exact: true }).fill('Household rice edited');
  await page.getByLabel(/I have reviewed/).check();
  await page.getByRole('button', { name: 'Save recipe', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Household rice edited', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Add to favourites', exact: true }).click();
  await page.getByRole('button', { name: 'Duplicate recipe', exact: true }).click();
  await expect(page).not.toHaveURL(new RegExp(`${id}$`));
  await page.getByRole('button', { name: 'Archive recipe', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Restore recipe', exact: true })).toBeVisible();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Delete recipe', exact: true }).click();
  await expect(page).toHaveURL(/\/recipes$/);
});
