import { test, expect } from '@playwright/test';
import { authenticatedHousehold, manualRecipe, write } from './fixtures';

test('catalogue correction, aliases, categories, conflicts and referenced deletion use the shared API', async ({ page }) => {
  await authenticatedHousehold(page);
  await page.goto('/ingredients');
  await page.getByLabel('Canonical ingredient name', { exact: true }).fill('Red capscum');
  await page.getByRole('button', { name: 'Save ingredient', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Ingredient saved.');
  await page.getByLabel('Canonical ingredient name', { exact: true }).fill('Red capsicum');
  await page.getByLabel('Keep the previous name as an alias when renaming').check();
  await page.getByRole('combobox', { name: 'Shopping category', exact: true }).selectOption({ label: 'Produce' });
  await page.getByRole('button', { name: 'Save ingredient', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Remove Red capscum', exact: true })).toBeVisible();
  await page.getByLabel('New alias', { exact: true }).fill('Red pepper');
  await page.getByRole('button', { name: 'Save alias', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Edit Red pepper', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Edit Red pepper', exact: true }).click();
  await page.getByLabel('Edit alias', { exact: true }).fill('Sweet red pepper');
  await page.getByRole('button', { name: 'Save alias', exact: true }).click();
  await page.getByLabel('Search names and aliases').fill('Sweet red pepper');
  await page.getByRole('button', { name: 'Search ingredients', exact: true }).click();
  await expect(page.locator('.ingredient-list > li')).toHaveCount(1);
  const catalogue = await (await page.request.get('/api/v1/ingredients?q=Sweet%20red%20pepper')).json();
  const ingredientId = catalogue.items[0].id;
  expect((await write(page, 'POST', '/api/v1/ingredients', { canonicalName: 'Beef mince' })).status()).toBe(201);
  await page.getByLabel('New alias', { exact: true }).fill('  BEEF mince ');
  await page.getByRole('button', { name: 'Save alias', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('name is already in use');
  await expect(page.getByLabel('New alias', { exact: true })).toHaveValue('  BEEF mince ');
  await page.getByLabel('New alias', { exact: true }).fill('');
  const recipe = await write(page, 'POST', '/api/v1/recipes', manualRecipe(ingredientId)); expect(recipe.status()).toBe(201);
  const recipeId = (await recipe.json()).id;
  await page.getByLabel('Canonical ingredient name', { exact: true }).fill('Red bell pepper');
  await page.getByLabel('Keep the previous name as an alias when renaming').check();
  await page.getByRole('button', { name: 'Save ingredient', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Ingredient saved.');
  const referenced = await page.request.get(`/api/v1/recipes/${recipeId}`);
  const preserved = await referenced.json(); expect(preserved.ingredients[0].ingredientId).toBe(ingredientId); expect(preserved.ingredients[0].ingredientName).toBe('Red bell pepper');
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Delete ingredient', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('ingredient is used');
  await page.getByRole('button', { name: 'Remove Sweet red pepper', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Alias removed.');
  await page.getByText('Manage shopping categories', { exact: true }).click();
  await page.getByLabel('Category name', { exact: true }).fill('Frozen');
  await page.getByLabel('Display order', { exact: true }).fill('4');
  await page.getByRole('button', { name: 'Save category', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Category saved.');
  await page.getByRole('combobox', { name: 'Shopping category', exact: true }).selectOption({ label: 'Frozen' });
  await page.getByRole('button', { name: 'Save ingredient', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Ingredient saved.');
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Delete category', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Category deleted.');
  await page.getByRole('button', { name: 'Reload ingredient and discard edits', exact: true }).click();
  await expect(page.getByRole('combobox', { name: 'Shopping category', exact: true })).toHaveValue('');
  const latestRecipe = await page.request.get(`/api/v1/recipes/${recipeId}`);
  expect((await write(page, 'DELETE', `/api/v1/recipes/${recipeId}`, undefined, latestRecipe.headers()['etag'])).status()).toBe(204);
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Delete ingredient', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Ingredient deleted.');
});
