import { test, expect, type Page } from '@playwright/test';
import { authenticatedHousehold, manualRecipe, write } from './fixtures';

async function updated(page: Page) { await expect(page.getByRole('status').filter({ hasText: 'Meal plan updated.' })).toBeVisible(); }

test('weekly planning, partial leftovers, releases, frozen recipes and atomic correction use shared authoritative results', async ({ page }) => {
  await authenticatedHousehold(page);
  const ingredient = await write(page, 'POST', '/api/v1/ingredients', { canonicalName: 'Red capsicum' }); expect(ingredient.status()).toBe(201);
  const ingredientId = (await ingredient.json()).id;
  const createdRecipe = await write(page, 'POST', '/api/v1/recipes', manualRecipe(ingredientId)); expect(createdRecipe.status()).toBe(201);
  const recipeId = (await createdRecipe.json()).id;
  await page.goto('/meal-planner');
  await expect(page.getByRole('heading', { name: 'Meal Planner', exact: true })).toBeVisible();
  await page.getByLabel('Week containing', { exact: true }).fill('2026-11-02');
  await page.getByLabel('Week containing', { exact: true }).press('Tab');
  await expect(page.getByLabel('Week containing', { exact: true })).toHaveValue('2026-11-02');
  await page.getByRole('button', { name: 'Cook a recipe', exact: true }).click();
  await page.getByRole('combobox', { name: 'Recipe', exact: true }).selectOption(recipeId);
  await page.getByLabel('Meal date', { exact: true }).fill('2026-11-02');
  await page.getByLabel('Portions to prepare', { exact: true }).fill('4');
  await page.getByLabel('Portions to eat at this meal', { exact: true }).fill('2');
  await page.getByRole('button', { name: 'Save meal', exact: true }).click(); await updated(page);
  const calendarPath = '/api/v1/meals?from=2026-11-02&to=2026-11-08';
  let calendar = await (await page.request.get(calendarPath)).json(); expect(calendar.items).toHaveLength(1);
  const cookId = calendar.items[0].id; const sourceId = calendar.items[0].cookingEvent.id;
  const cookCard = page.locator(`[data-meal-id="${cookId}"]`);
  await expect(cookCard).toContainText('Prepare 4 portions. Eat 2.');
  await page.getByRole('button', { name: 'Schedule leftovers', exact: true }).click();
  await page.getByRole('combobox', { name: 'Source cooking event', exact: true }).selectOption(sourceId);
  await page.getByLabel('Leftover meal date', { exact: true }).fill('2026-11-03');
  await page.getByLabel('Planned leftover portions', { exact: true }).fill('2');
  await page.getByRole('button', { name: 'Schedule leftover meal', exact: true }).click(); await updated(page);
  calendar = await (await page.request.get(calendarPath)).json(); const leftover = calendar.items.find((item: { type: string }) => item.type === 'leftovers');
  const leftCard = page.locator(`[data-meal-id="${leftover.id}"]`); await expect(leftCard).toContainText('Not confirmed');
  let balance = await (await page.request.get(`/api/v1/cooking-events/${sourceId}/leftovers`)).json(); expect(balance.basis).toBe('planned'); expect(balance.availablePortions).toBe('0');
  await cookCard.getByRole('button', { name: /^Cooking and leftovers/ }).click();
  await page.getByRole('button', { name: 'Confirm cooking quantities', exact: true }).click(); await updated(page);
  await leftCard.getByRole('button', { name: /^Edit / }).click();
  await page.getByText('Confirm or correct leftover consumption', { exact: true }).click();
  await page.getByLabel('Total portions consumed at this meal', { exact: true }).fill('1.5');
  await page.getByLabel('Portions still reserved after confirmation', { exact: true }).fill('0.5');
  await page.getByRole('button', { name: 'Confirm leftover consumption', exact: true }).click(); await updated(page);
  await leftCard.getByRole('button', { name: /^Edit / }).click();
  await page.getByLabel('Remaining reservation', { exact: true }).fill('0');
  await page.getByRole('button', { name: 'Save leftover plan', exact: true }).click(); await updated(page);
  balance = await (await page.request.get(`/api/v1/cooking-events/${sourceId}/leftovers`)).json(); expect(balance.availablePortions).toBe('0.5');
  const original = balance.allocations.find((item: { mealId: string }) => item.mealId === leftover.id).allocation;
  expect(original.plannedPortions).toBe('2'); expect(original.consumedPortions).toBe('1.5'); expect(original.reservedRemainder).toBe('0');
  await page.getByRole('button', { name: 'Schedule leftovers', exact: true }).click();
  await page.getByRole('combobox', { name: 'Source cooking event', exact: true }).selectOption(sourceId);
  await page.getByLabel('Leftover meal date', { exact: true }).fill('2026-11-04');
  await expect(page.getByLabel('Planned leftover portions', { exact: true })).toHaveValue('0.5');
  await page.getByRole('button', { name: 'Schedule leftover meal', exact: true }).click(); await updated(page);
  calendar = await (await page.request.get(calendarPath)).json(); const secondLeftover = calendar.items.find((item: { type: string; date: string }) => item.type === 'leftovers' && item.date === '2026-11-04');
  const currentRecipe = await page.request.get(`/api/v1/recipes/${recipeId}`);
  expect((await write(page, 'PUT', `/api/v1/recipes/${recipeId}`, { ...manualRecipe(ingredientId), title: 'Revised capsicum salad' }, currentRecipe.headers()['etag'])).status()).toBe(200);
  await page.getByRole('button', { name: 'Refresh calendar', exact: true }).click();
  await expect(cookCard.getByRole('heading', { name: 'Pepper salad', exact: true })).toBeVisible();
  await cookCard.getByRole('button', { name: /^Cooking and leftovers/ }).click();
  await page.getByRole('button', { name: 'Review latest recipe', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Latest recipe', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Apply reviewed recipe refresh', exact: true }).click(); await updated(page);
  await expect(cookCard.getByRole('heading', { name: 'Revised capsicum salad', exact: true })).toBeVisible();
  await cookCard.getByRole('button', { name: /^Cooking and leftovers/ }).click();
  await page.getByLabel('Actual portions prepared', { exact: true }).fill('3');
  await page.getByLabel('Actual portions eaten at the cooking meal', { exact: true }).fill('1.5');
  await page.getByRole('button', { name: 'Save actual correction', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Review related leftover meals', exact: true })).toBeVisible();
  await page.locator(`#resolution-action-${secondLeftover.id}`).selectOption('release');
  await page.locator(`#resolution-reserved-${secondLeftover.id}`).fill('0');
  await page.getByRole('button', { name: 'Apply all reviewed changes', exact: true }).click(); await updated(page);
  balance = await (await page.request.get(`/api/v1/cooking-events/${sourceId}/leftovers`)).json();
  expect(balance.actualPrepared).toBe('3'); expect(balance.actualEaten).toBe('1.5'); expect(balance.availablePortions).toBe('0');
  expect(balance.plannedPrepared).toBe('4');
  expect(balance.allocations.find((item: { mealId: string }) => item.mealId === leftover.id).allocation.consumedPortions).toBe('1.5');
  expect(balance.allocations.find((item: { mealId: string }) => item.mealId === secondLeftover.id).allocation.reservedRemainder).toBe('0');
  await expect(page.locator(`[data-meal-id="${secondLeftover.id}"]`)).toBeVisible();
  const ingredientBefore = await page.request.get(`/api/v1/ingredients/${ingredientId}`);
  const renamed = await write(page, 'PUT', `/api/v1/ingredients/${ingredientId}`, { canonicalName: 'Capsicum corrected' }, ingredientBefore.headers()['etag']);
  expect(renamed.status()).toBe(200);
  const liveRecipe = await page.request.get(`/api/v1/recipes/${recipeId}`);
  expect((await write(page, 'PUT', `/api/v1/recipes/${recipeId}`, { ...manualRecipe(ingredientId), ingredients: [] }, liveRecipe.headers()['etag'])).status()).toBe(200);
  // The live recipe no longer references this ingredient; the immutable cooking snapshot still does.
  expect((await write(page, 'DELETE', `/api/v1/ingredients/${ingredientId}`, undefined, renamed.headers()['etag'])).status()).toBe(409);
  const frozenMeal = await (await page.request.get(`/api/v1/meals/${cookId}`)).json();
  expect(frozenMeal.cookingEvent.recipeSnapshot.ingredients[0].ingredientName).toBe('Red capsicum');
});
